import * as Phaser from 'https://cdn.jsdelivr.net/npm/phaser@3.90.0/dist/phaser.esm.js';
import combat from './config/combat.json?v=17' with {type:'json'};
import {palette} from './theme/palette.js?v=17';
import {Boot} from './scenes/Boot.js?v=17';
import {Title} from './scenes/Title.js?v=17';
import {Camp} from './scenes/Camp.js?v=17';
import {Debug} from './scenes/Debug.js?v=17';
import {PuzzleRoom} from './scenes/PuzzleRoom.js?v=17';
import {Arena} from './scenes/Arena.js?v=17';
import {Save} from './systems/Save.js?v=17';
const game=new Phaser.Game({type:Phaser.AUTO,parent:'game',width:combat.resolution.width,height:combat.resolution.height,backgroundColor:palette.background,scale:{mode:Phaser.Scale.FIT,autoCenter:Phaser.Scale.CENTER_BOTH},dom:{createContainer:true},input:{activePointers:combat.input.pointers,gamepad:true},physics:{default:'arcade',arcade:{gravity:{y:combat.movement.gravity},debug:false}},fps:{target:combat.performance.normalFps,forceSetTimeOut:false},scene:[Boot,Title,Camp,Arena,PuzzleRoom,Debug]});
document.addEventListener('visibilitychange',()=>{if(document.hidden&&game.settings)Save.write(game.settings,game.settings.checkpoint)});
if('serviceWorker'in navigator)window.addEventListener('load',()=>navigator.serviceWorker.register('./sw.js?v=17').catch(()=>{}));
export default game;
