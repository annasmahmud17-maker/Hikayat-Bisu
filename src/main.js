import * as Phaser from 'https://cdn.jsdelivr.net/npm/phaser@3.90.0/dist/phaser.esm.js';
import cfg from './config/combat.json?v=z2-1' with {type:'json'};
import {palette} from './theme/palette.js?v=z2-1';
import {Boot} from './scenes/Boot.js?v=z2-1';
import {Title} from './scenes/Title.js?v=z2-1';
import {Camp} from './scenes/Camp.js?v=z2-1';
import {Stage} from './scenes/Stage.js?v=z2-1';
import {Map} from './scenes/Map.js?v=z2-1';
import {Repository} from './scenes/Repository.js?v=z2-1';
import {Debug} from './scenes/Debug.js?v=z2-1';
import {Save} from './systems/Save.js?v=z2-1';
const game=new Phaser.Game({type:Phaser.AUTO,parent:'game',width:cfg.resolution.width,height:cfg.resolution.height,backgroundColor:palette.background,scale:{mode:Phaser.Scale.FIT,autoCenter:Phaser.Scale.CENTER_BOTH},input:{activePointers:cfg.pointers,gamepad:true},fps:{target:cfg.fps,forceSetTimeOut:true,smoothStep:false},scene:[Boot,Title,Camp,Stage,Map,Repository,Debug]});
document.addEventListener('visibilitychange',()=>{if(document.hidden&&game.settings)Save.write(game.settings)});
export default game;
